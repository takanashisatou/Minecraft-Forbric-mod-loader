/**
 * MergedBaseBuilder's half of the paired-hook facade increment: the restored-hooks manifest embedded in the
 * merged base, and the report's machine-readable facade-candidates section. Whether a composition is accepted
 * is AdditiveMethodMerger's own grammar, tested there; these tests pin the two shapes OTHER tools parse — the
 * kernel's ComposedHookManifest reads one {@code <pairId> <host>#<name><desc> paired-facade} row per composed
 * site, and LostHookAttribution reads the candidates section's {@code candidate <neoHook> <forgeHook>
 * declines=<n> sites=...} rows — plus the empty-table baseline, since v1 ships the pair table empty.
 */
class MergedBaseBuilderManifestTest {
	@TempDir Path directory;
	private static final String OWNER = "net/minecraft/EntryHookProbe";
	private static final String CHOOSE = "choose(Ljava/util/Optional;)I";
	private static final String NEO_FILTER =
			AdditiveMethodMergerTest.NEO + ".filter(Ljava/util/Optional;)Ljava/util/Optional;";
	private static final String FORGE_FILTER =
			AdditiveMethodMergerTest.FORGE + ".filter(Ljava/util/Optional;)Ljava/util/Optional;";
	private static final String MANIFEST = "META-INF/forbric/restored-hooks.txt";

	@Test
	void theShippedPairTableLoadsEmpty() {
		assertTrue(MergedBaseBuilder.loadFacadePairTable().isEmpty(),
				"v1 ships the mechanism only; reviewed pairs are enabled on a jar-equipped machine later");
	}

	@Test
	void manifestIsWrittenWithHeaderOnlyWhenNoPairComposes() throws Exception {
		// An entry-prefix decline exercises the additive decision path without any facade acceptance.
		MethodNode vanilla = AdditiveMethodMergerTest.arithmetic();
		Build result = build(new MergedBaseBuilder(), vanilla,
				AdditiveMethodMergerTest.prefix(vanilla, AdditiveMethodMergerTest.FORGE),
				AdditiveMethodMergerTest.prefix(vanilla, AdditiveMethodMergerTest.NEO), false);
		String manifest = result.entry(MANIFEST);
		assertNotNull(manifest, "the merged base always carries " + MANIFEST);
		List<String> lines = manifest.lines().toList();
		assertEquals(4, lines.size(), "header only, no rows: " + manifest);
		for (String line : lines) assertTrue(line.startsWith("#"), "a header comment: " + line);
		assertTrue(lines.get(0).startsWith("# generated by MergedBaseBuilder"), lines.get(0));
		assertTrue(lines.contains("# inputs: vanilla=vanilla.jar forge=forge.jar neo=neo.jar"), manifest);
		assertTrue(result.report.contains(
				"paired hooks restored via facade: 0 site(s) listed in " + MANIFEST), result.report);
		assertTrue(result.report.contains("=== machine-readable: paired-hook facade candidates"), result.report);
		assertTrue(result.report.contains("# (none)"), result.report);
	}

	@Test
	void manifestRowsAreRenderedExactly() {
		String expected = "# generated by MergedBaseBuilder; do not edit — rebuilt with every merged base\n"
				+ "# one row per paired-hook site composed through net/forbric/kernel/runtime/ComposedHook:\n"
				+ "# <pairId> <hostInternalName>#<hostName><hostDesc> paired-facade\n"
				+ "# inputs: vanilla=v.jar forge=f.jar neo=n.jar\n"
				+ "portalSpawn net/minecraft/BaseFireBlock#onTrySpawnPortal()V paired-facade\n";
		assertEquals(expected, MergedBaseBuilder.restoredHooksManifest(
				List.of("portalSpawn net/minecraft/BaseFireBlock#onTrySpawnPortal()V paired-facade"),
				"v.jar", "f.jar", "n.jar"));
	}

	@Test
	void aListedPairComposesThroughTheFacadeAndIsListedInTheManifest() throws Exception {
		AdditiveMethodMerger.HookPairs pairs = AdditiveMethodMerger.HookPairs.parse(
				List.of("pairFilter " + NEO_FILTER + " " + FORGE_FILTER));
		Build result = build(new MergedBaseBuilder(Set.of(), pairs), AdditiveMethodMergerTest.choosing(),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.FORGE),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.NEO),
				true);
		// The decision row and the manifest row agree, in the shapes LostHookAttribution and the kernel parse.
		assertTrue(result.report.contains(OWNER + "#" + CHOOSE
				+ " ACCEPTED paired hooks restored via facade pairFilter (1 site(s))"), result.report);
		assertFalse(result.report.contains("(forge hook lost)"), result.report);
		String manifest = result.entry(MANIFEST);
		assertNotNull(manifest);
		assertEquals(List.of("pairFilter " + OWNER + "#" + CHOOSE + " paired-facade"),
				manifest.lines().filter(line -> !line.startsWith("#")).toList(), manifest);
		// The merged body calls the facade, and neither family's own hook call survives in it.
		assertEquals(List.of(AdditiveMethodMerger.COMPOSED_HOOK_FACADE, "java/util/Optional"), calls(result.method));
		// The attribution tool's own manifest reader accepts the bytes.
		assertTrue(LostHookAttribution.restoredHookManifest(result.jar)
				.contains("pairFilter " + OWNER + "#" + CHOOSE));
		// ... and its report parser classifies the decision row as a facade restoration of this site.
		LostHookAttribution.Report dispositions = LostHookAttribution.report(result.reportPath);
		assertEquals(1, dispositions.facadeRestorations().size());
		assertEquals("pairFilter", dispositions.facadeRestorations().get(0).pairId());
		assertEquals(OWNER, dispositions.facadeRestorations().get(0).owner());
		assertEquals(CHOOSE, dispositions.facadeRestorations().get(0).method());
		// The composed body links and runs with the kernel facade defined beside the probe families.
		assertEquals(1, invokeChoose(result.bytes, Optional.of("portal")));
		assertEquals(0, invokeChoose(result.bytes, Optional.empty()));
	}

	@Test
	void aReviewedPairStillComposesInlineWithoutAManifestRow() throws Exception {
		// The pre-facade path (REVIEWED_RESTORATIONS shape) is untouched: an inline composition is not a facade
		// site, so the manifest stays header-only and the candidates section stays empty.
		Set<String> reviewed = Set.of(NEO_FILTER + " -> " + FORGE_FILTER);
		Build result = build(new MergedBaseBuilder(reviewed), AdditiveMethodMergerTest.choosing(),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.FORGE),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.NEO),
				true);
		assertTrue(result.report.contains(OWNER + "#" + CHOOSE + " ACCEPTED paired hooks at identical vanilla "
				+ "points"), result.report);
		String manifest = result.entry(MANIFEST);
		assertNotNull(manifest);
		assertTrue(manifest.lines().allMatch(line -> line.startsWith("#")), manifest);
		assertTrue(result.report.contains("# (none)"), result.report);
	}

	@Test
	void anUnmappedComposablePairIsListedAsAFacadeCandidate() throws Exception {
		Build result = build(new MergedBaseBuilder(Set.of()), AdditiveMethodMergerTest.choosing(),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.FORGE),
				AdditiveMethodMergerTest.filtered(AdditiveMethodMergerTest.choosing(), AdditiveMethodMergerTest.NEO),
				true);
		// The human-readable rows are unchanged...
		assertTrue(result.report.contains(OWNER + "#" + CHOOSE + " DECLINED paired hooks align, but no runtime "
				+ "stand-down is reviewed: restoring " + FORGE_FILTER), result.report);
		assertTrue(result.report.contains(OWNER + "#" + CHOOSE + " (forge hook lost)"), result.report);
		// ...and the machine-readable section names the pair, neo hook first, with its decline count and sites.
		// (The report file uses the platform line separator, so the row is anchored on its prefix, not on \n.)
		assertTrue(result.report.contains("\ncandidate " + NEO_FILTER + " " + FORGE_FILTER
				+ " declines=1 sites=" + OWNER + "#" + CHOOSE), result.report);
		assertTrue(result.report.contains("facade candidates: 1 refusal(s) across 1 pair(s)"), result.report);
		// The attribution tool's report parser reads the same section: one candidate, its site the refusal's host.
		LostHookAttribution.Report dispositions = LostHookAttribution.report(result.reportPath);
		assertEquals(List.of(new LostHookAttribution.FacadeCandidate(NEO_FILTER, FORGE_FILTER, 1,
				List.of(OWNER + "#" + CHOOSE))), dispositions.facadeCandidates());
		assertTrue(dispositions.facadeRestorations().isEmpty());
	}

	@Test
	void aSuperclassRebasedHostStillListsTheCandidateNeoFirst() throws Exception {
		// Only Forge injects a real superclass, so the merge base flips to Forge's class and the restored
		// (dropped) hook is Neo's; the candidate row is still printed neo hook first — the pair table's column
		// order, and the order LostHookAttribution's candidate row parses.
		MethodNode vanilla = AdditiveMethodMergerTest.choosing();
		Path v = jar("vanilla.jar", OWNER, AdditiveMethodMergerTest.classBytes(OWNER, vanilla));
		Path f = jar("forge.jar", OWNER, classBytesOn(OWNER, "net/minecraftforge/ForgeBase",
				AdditiveMethodMergerTest.filtered(vanilla, AdditiveMethodMergerTest.FORGE)));
		Path n = jar("neo.jar", OWNER, AdditiveMethodMergerTest.classBytes(OWNER,
				AdditiveMethodMergerTest.filtered(vanilla, AdditiveMethodMergerTest.NEO)));
		Build result = run(new MergedBaseBuilder(Set.of()), v, f, n, true);
		assertTrue(result.report.contains(OWNER + "#" + CHOOSE + " (neo hook lost)"), result.report);
		assertTrue(result.report.contains("\ncandidate " + NEO_FILTER + " " + FORGE_FILTER
				+ " declines=1 sites=" + OWNER + "#" + CHOOSE), result.report);
		LostHookAttribution.FacadeCandidate candidate =
				LostHookAttribution.report(result.reportPath).facadeCandidates().get(0);
		assertEquals(NEO_FILTER, candidate.neoHook());
		assertEquals(FORGE_FILTER, candidate.forgeHook());
	}

	private Build build(MergedBaseBuilder builder, MethodNode vanilla, MethodNode forge, MethodNode neo,
			boolean runtimes) throws Exception {
		Path v = jar("vanilla.jar", OWNER, AdditiveMethodMergerTest.classBytes(OWNER, vanilla));
		Path f = jar("forge.jar", OWNER, AdditiveMethodMergerTest.classBytes(OWNER, forge));
		Path n = jar("neo.jar", OWNER, AdditiveMethodMergerTest.classBytes(OWNER, neo));
		return run(builder, v, f, n, runtimes);
	}

	private Build run(MergedBaseBuilder builder, Path v, Path f, Path n, boolean runtimes) throws Exception {
		Path forgeRuntime = runtimes ? jar("forge-runtime.jar", AdditiveMethodMergerTest.FORGE,
				AdditiveMethodMergerTest.hookClass(AdditiveMethodMergerTest.FORGE)) : null;
		Path neoRuntime = runtimes ? jar("neo-runtime.jar", AdditiveMethodMergerTest.NEO,
				AdditiveMethodMergerTest.hookClass(AdditiveMethodMergerTest.NEO)) : null;
		Path merged = directory.resolve("merged.jar"), report = directory.resolve("report.txt");
		builder.run(v, f, n, merged, report, forgeRuntime, neoRuntime);
		try (ZipFile zip = new ZipFile(merged.toFile())) {
			ZipEntry ownerEntry = zip.getEntry(OWNER + ".class");
			assertNotNull(ownerEntry, "the probe class survives the merge");
			byte[] bytes = zip.getInputStream(ownerEntry).readAllBytes();
			ClassNode output = new ClassNode();
			new ClassReader(bytes).accept(output, 0);
			return new Build(output.methods.get(0), Files.readString(report), bytes, merged, report);
		}
	}

	private Path jar(String name, String owner, byte[] bytes) throws Exception {
		Path path = directory.resolve(name);
		try (ZipOutputStream zip = new ZipOutputStream(Files.newOutputStream(path))) {
			zip.putNextEntry(new ZipEntry(owner + ".class"));
			zip.write(bytes);
			zip.closeEntry();
		}
		return path;
	}

	/** As {@link AdditiveMethodMergerTest#classBytes}, but on an explicit superclass (the rebased-base fixture). */
	private static byte[] classBytesOn(String name, String superName, MethodNode method) {
		ClassWriter writer = new ClassWriter(ClassWriter.COMPUTE_FRAMES | ClassWriter.COMPUTE_MAXS);
		writer.visit(Opcodes.V17, Opcodes.ACC_PUBLIC, name, null, superName, null);
		method.accept(writer);
		writer.visitEnd();
		return writer.toByteArray();
	}

	private static List<String> calls(MethodNode method) {
		List<String> out = new ArrayList<>();
		for (AbstractInsnNode instruction : method.instructions) {
			if (instruction instanceof MethodInsnNode call) out.add(call.owner);
		}
		return out;
	}

	/** Runs the merged {@code choose} with the probe hook families and the kernel facade defined beside it. */
	private static int invokeChoose(byte[] bytes, Optional<?> found) throws Exception {
		class Loader extends ClassLoader {
			Class<?> define(String name, byte[] bytes) {
				return defineClass(name.replace('/', '.'), bytes, 0, bytes.length);
			}
		}
		Loader loader = new Loader();
		loader.define(AdditiveMethodMergerTest.NEO, AdditiveMethodMergerTest.hookClass(AdditiveMethodMergerTest.NEO));
		loader.define(AdditiveMethodMergerTest.FORGE, AdditiveMethodMergerTest.hookClass(AdditiveMethodMergerTest.FORGE));
		loader.define(AdditiveMethodMerger.COMPOSED_HOOK_FACADE, AdditiveMethodMergerTest.composedHookClass());
		return (int) loader.define(OWNER, bytes).getMethod("choose", Optional.class).invoke(null, found);
	}

	private record Build(MethodNode method, String report, byte[] bytes, Path jar, Path reportPath) {
		/** The text of entry {@code name} in the merged jar, or null when the entry is absent. */
		String entry(String name) throws Exception {
			try (ZipFile zip = new ZipFile(jar.toFile())) {
				ZipEntry entry = zip.getEntry(name);
				return entry == null ? null
						: new String(zip.getInputStream(entry).readAllBytes(), StandardCharsets.UTF_8);
			}
		}
	}
}
